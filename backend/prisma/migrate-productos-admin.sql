BEGIN;

CREATE TABLE IF NOT EXISTS public.productos_admin (
  id integer PRIMARY KEY,
  legacy_id integer,
  manual boolean NOT NULL DEFAULT false,
  titulo text,
  categoria text,
  precio_proveedor text,
  precio_final text,
  imagen text,
  galeria_personalizada boolean NOT NULL DEFAULT false,
  orden_personalizado integer,
  mas_vendido boolean NOT NULL DEFAULT false,
  orden_mas_vendidos integer,
  en_oferta boolean NOT NULL DEFAULT false,
  orden_ofertas integer,
  base_titulo text,
  base_precio text,
  base_categoria text,
  base_imagen text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.productos_admin
  ADD COLUMN IF NOT EXISTS legacy_id integer;
CREATE UNIQUE INDEX IF NOT EXISTS productos_admin_legacy_id_key
  ON public.productos_admin (legacy_id);

CREATE TABLE IF NOT EXISTS public.productos_admin_imagenes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_id integer NOT NULL REFERENCES public.productos_admin (id) ON DELETE CASCADE,
  url text NOT NULL,
  orden integer NOT NULL DEFAULT 0,
  CONSTRAINT productos_admin_imagenes_producto_id_orden_key UNIQUE (producto_id, orden)
);

INSERT INTO public.productos_admin (
  id,
  manual,
  titulo,
  categoria,
  precio_proveedor,
  precio_final,
  imagen,
  galeria_personalizada,
  base_titulo,
  base_precio,
  base_categoria,
  base_imagen
)
SELECT
  (settings_row.value::jsonb ->> 'id')::integer,
  COALESCE((settings_row.value::jsonb ->> 'manual')::boolean, false),
  settings_row.value::jsonb ->> 'titulo',
  settings_row.value::jsonb ->> 'categoria',
  settings_row.value::jsonb ->> 'precioProveedor',
  settings_row.value::jsonb ->> 'precioFinal',
  settings_row.value::jsonb ->> 'imagen',
  (settings_row.value::jsonb ? 'imagenes'),
  settings_row.value::jsonb #>> '{baseSnapshot,titulo}',
  settings_row.value::jsonb #>> '{baseSnapshot,precio}',
  settings_row.value::jsonb #>> '{baseSnapshot,categoria}',
  settings_row.value::jsonb #>> '{baseSnapshot,imagen}'
FROM public.app_settings AS settings_row
WHERE settings_row.key LIKE 'producto-admin:%'
  AND jsonb_typeof(settings_row.value::jsonb) = 'object'
  AND settings_row.value::jsonb ? 'id'
ON CONFLICT (id) DO NOTHING;

INSERT INTO public.productos_admin_imagenes (producto_id, url, orden)
SELECT
  (settings_row.value::jsonb ->> 'id')::integer,
  fotos.url,
  (fotos.ordinalidad - 1)::integer
FROM public.app_settings AS settings_row
CROSS JOIN LATERAL jsonb_array_elements_text(
  CASE
    WHEN jsonb_typeof(settings_row.value::jsonb -> 'imagenes') = 'array'
      THEN settings_row.value::jsonb -> 'imagenes'
    ELSE '[]'::jsonb
  END
) WITH ORDINALITY AS fotos(url, ordinalidad)
WHERE settings_row.key LIKE 'producto-admin:%'
  AND jsonb_typeof(settings_row.value::jsonb) = 'object'
  AND settings_row.value::jsonb ? 'id'
ON CONFLICT (producto_id, orden) DO NOTHING;

WITH offset_id AS (
  SELECT COALESCE(MAX(-id), 0) AS valor
  FROM public.productos_admin
  WHERE id < 0
),
pendientes AS (
  SELECT
    manuales.*,
    ROW_NUMBER() OVER (ORDER BY manuales.id) AS fila
  FROM public.productos_agregados_a_mano AS manuales
  WHERE NOT EXISTS (
    SELECT 1
    FROM public.productos_admin AS existentes
    WHERE existentes.legacy_id = manuales.id
  )
)
INSERT INTO public.productos_admin (
  id,
  legacy_id,
  manual,
  titulo,
  categoria,
  precio_proveedor,
  imagen
)
SELECT
  -(offset_id.valor + pendientes.fila)::integer,
  pendientes.id,
  true,
  COALESCE(NULLIF(pendientes.titulo, ''), 'Producto manual'),
  COALESCE(pendientes.categoria, ''),
  COALESCE(pendientes.precio, '0'),
  COALESCE(pendientes.imagen, '')
FROM pendientes
CROSS JOIN offset_id
ON CONFLICT (legacy_id) DO NOTHING;

WITH configuracion AS (
  SELECT value::jsonb AS datos
  FROM public.app_settings
  WHERE key = 'productos-admin-config'
),
orden AS (
  SELECT
    elemento.valor::integer AS id,
    (elemento.ordinalidad - 1)::integer AS posicion
  FROM configuracion
  CROSS JOIN LATERAL jsonb_array_elements_text(
    CASE WHEN jsonb_typeof(datos -> 'orden') = 'array'
      THEN datos -> 'orden' ELSE '[]'::jsonb END
  ) WITH ORDINALITY AS elemento(valor, ordinalidad)
),
mas_vendidos AS (
  SELECT
    elemento.valor::integer AS id,
    (elemento.ordinalidad - 1)::integer AS posicion
  FROM configuracion
  CROSS JOIN LATERAL jsonb_array_elements_text(
    CASE WHEN jsonb_typeof(datos -> 'masVendidos') = 'array'
      THEN datos -> 'masVendidos' ELSE '[]'::jsonb END
  ) WITH ORDINALITY AS elemento(valor, ordinalidad)
),
ofertas AS (
  SELECT
    elemento.valor::integer AS id,
    (elemento.ordinalidad - 1)::integer AS posicion
  FROM configuracion
  CROSS JOIN LATERAL jsonb_array_elements_text(
    CASE WHEN jsonb_typeof(datos -> 'ofertas') = 'array'
      THEN datos -> 'ofertas' ELSE '[]'::jsonb END
  ) WITH ORDINALITY AS elemento(valor, ordinalidad)
),
ids AS (
  SELECT id FROM orden
  UNION
  SELECT id FROM mas_vendidos
  UNION
  SELECT id FROM ofertas
)
INSERT INTO public.productos_admin (
  id,
  orden_personalizado,
  mas_vendido,
  orden_mas_vendidos,
  en_oferta,
  orden_ofertas
)
SELECT
  ids.id,
  orden.posicion,
  mas_vendidos.id IS NOT NULL,
  mas_vendidos.posicion,
  ofertas.id IS NOT NULL,
  ofertas.posicion
FROM ids
LEFT JOIN orden ON orden.id = ids.id
LEFT JOIN mas_vendidos ON mas_vendidos.id = ids.id
LEFT JOIN ofertas ON ofertas.id = ids.id
ON CONFLICT (id) DO UPDATE SET
  orden_personalizado = COALESCE(productos_admin.orden_personalizado, EXCLUDED.orden_personalizado),
  mas_vendido = productos_admin.mas_vendido OR EXCLUDED.mas_vendido,
  orden_mas_vendidos = COALESCE(productos_admin.orden_mas_vendidos, EXCLUDED.orden_mas_vendidos),
  en_oferta = productos_admin.en_oferta OR EXCLUDED.en_oferta,
  orden_ofertas = COALESCE(productos_admin.orden_ofertas, EXCLUDED.orden_ofertas);

COMMIT;
